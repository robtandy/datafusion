/// The number of operators of the operator tree below (and including)
/// `operator`.
fn count_operators(operator: &Arc<dyn PhysicalOperator>) -> usize {
    1 + operator
        .children()
        .iter()
        .map(count_operators)
        .sum::<usize>()
}

/// The number of nodes of the DataFusion plan `plan`.
fn count_nodes(plan: &Arc<dyn ExecutionPlan>) -> usize {
    1 + plan.children().into_iter().map(count_nodes).sum::<usize>()
}

/// How the pipeline engine lowered the plan of a query.
#[derive(Debug)]
pub(crate) struct Lowering {
    /// The number of operators of the lowered operator tree.
    pub(crate) operators: usize,
    /// The DataFusion plans that run in `BridgeOperator`s, on one line each.
    pub(crate) bridged: Vec<String>,
    /// The number of nodes of the DataFusion plans that run in
    /// `BridgeOperator`s.
    pub(crate) bridged_nodes: usize,
    /// The names of the roots of the DataFusion plans that run in
    /// `BridgeOperator`s.
    pub(crate) roots: Vec<String>,
}

impl Lowering {
    /// The lowering of `plan`, a plan of a `SessionContext` with
    /// `PipelineQueryPlanner`.
    pub(crate) fn of(plan: &Arc<dyn ExecutionPlan>) -> Result<Self> {
        let root = plan.downcast_ref::<PipelineRootExec>().ok_or_else(|| {
            DataFusionError::Internal(format!(
                "The pipeline engine did not plan the query, its root is {}",
                plan.name()
            ))
        })?;
        let plans = bridged_plans(root.operator());
        let bridged = plans
            .iter()
            .map(|plan| displayable(plan.as_ref()).one_line().to_string())
            .map(|line| line.trim_end().to_string())
            .collect::<Vec<_>>();
        Ok(Self {
            operators: count_operators(root.operator()),
            bridged,
            bridged_nodes: plans.iter().map(count_nodes).sum(),
            roots: plans.iter().map(|plan| plan.name().to_string()).collect(),
        })
    }

    /// The number of native (not bridged) operators.
    pub(crate) fn native_operators(&self) -> usize {
        self.operators - self.bridged.len()
    }
}

/// The lowerings of the 22 TPC-H queries by the pipeline engine over
/// `source`, in query order.
