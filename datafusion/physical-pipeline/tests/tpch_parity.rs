/// Deterministic synthetic TPC-H data.
///
/// The tables follow the rules of the TPC-H specification (and of its data
/// generator `dbgen`) closely enough for all queries to return meaningful
/// results: the standard schema with `DECIMAL(15, 2)` prices, `DATE` dates
/// and `Utf8View` strings (the string type of DataFusion's SQL tables and
/// Parquet scans), the 25 nations of the 5 regions, 4 suppliers per part,
/// sparse order keys, customers whose key is a multiple of 3 have no orders,
/// ship, commit and receipt dates relative to the order date, return flags
/// and line statuses that depend on the "current date" 1995-06-17, order
/// prices and statuses derived from their lineitems, text columns with the
/// patterns the queries look for (`%green%`, `forest%`, `%BRASS`,
/// `%special%requests%`, `%Customer%Complaints%`, ...).
///
/// On top of that, the data has
///
/// * skew: 15% of the lineitems are of 10 "hot" parts (the first three of
///   which are of the kinds of parts that TPC-H Q17 and Q19 look for), 6% of
///   the orders are of 3 "hot" customers, and every 397th order is a bulk
///   order of 7 lineitems with large quantities (which Q18 looks for);
/// * nulls in some columns (`o_custkey`, `c_phone`, `c_acctbal` and the
///   comments), so that joins see null keys and filters and aggregates see
///   null values. Keys and the columns of the `NOT IN` subquery of Q16 are
///   not nullable, as in TPC-H.
///
/// All values are generated by a fixed pseudo-random sequence ([`Rng`]), so
/// the data never changes.
