    fn orders_and_lineitems(
        cardinalities: Cardinalities,
    ) -> Result<(RecordBatch, RecordBatch)> {
        let mut rng = Rng::new(7);
        let clerks = (cardinalities.suppliers / 10).max(1);
        let mut keys = vec![];
        let mut customers = vec![];
        let mut statuses = vec![];
        let mut total_prices = vec![];
        let mut order_dates = vec![];
        let mut priorities = vec![];
        let mut order_clerks = vec![];
        let mut ship_priorities = vec![];
        let mut order_comments = vec![];
        let mut lines = Lineitems::default();
        for index in 0..cardinalities.orders {
            // Sparse keys: 8 keys out of every 32.
            let key = (index / 8) * 32 + index % 8 + 1;
            let customer = match rng.int(0, 999) {
                0..=4 => None,
                5..=64 => Some(HOT_CUSTOMERS[rng.int(0, 2) as usize]),
                _ => {
                    let customer = rng.int(1, cardinalities.customers);
                    Some(if customer % 3 == 0 {
                        customer - 1
                    } else {
                        customer
                    })
                }
            };
            let order_date =
                rng.int(i64::from(START_DATE), i64::from(LAST_ORDER_DATE)) as i32;
            let bulk = index % BULK_ORDER_PERIOD == BULK_ORDER_PERIOD - 1;
            let count = if bulk { 7 } else { rng.int(1, 7) };
            let mut total_price = 0;
            let (mut shipped, mut open) = (0, 0);
            for number in 1..=count {
                let part = if rng.chance(150) {
                    rng.int(1, HOT_PARTS.min(cardinalities.parts))
                } else {
                    rng.int(1, cardinalities.parts)
                };
                let supplier =
                    part_suppliers(part, cardinalities.suppliers)[rng.int(0, 3) as usize];
                let quantity = if bulk {
                    rng.int(45, 50)
                } else {
                    rng.int(1, 50)
                };
                let price = quantity * retail_price(part);
                let discount = rng.int(0, 10);
                let tax = rng.int(0, 8);
                total_price += (price * (100 + tax) * (100 - discount) + 5_000) / 10_000;
                let ship_date = order_date + rng.int(1, 121) as i32;
                let commit_date = order_date + rng.int(30, 90) as i32;
                let receipt_date = ship_date + rng.int(1, 30) as i32;
                let return_flag = if receipt_date <= CURRENT_DATE {
                    if rng.chance(500) { "R" } else { "A" }
                } else {
                    "N"
                };
                let line_status = if ship_date > CURRENT_DATE {
                    open += 1;
                    "O"
                } else {
                    shipped += 1;
                    "F"
                };
                lines.orders.push(key);
                lines.parts.push(part);
                lines.suppliers.push(supplier);
                lines.numbers.push(number as i32);
                lines.quantities.push(Some(quantity * 100));
                lines.prices.push(Some(price));
                lines.discounts.push(Some(discount));
                lines.taxes.push(Some(tax));
                lines.return_flags.push(return_flag);
                lines.line_statuses.push(line_status);
                lines.ship_dates.push(ship_date);
                lines.commit_dates.push(commit_date);
                lines.receipt_dates.push(receipt_date);
                lines.instructions.push(rng.pick(&INSTRUCTIONS));
                lines.ship_modes.push(rng.pick(&SHIP_MODES));
                lines.comments.push((!rng.chance(5)).then(|| rng.comment()));
            }
            keys.push(key);
            customers.push(customer);
            statuses.push(match (shipped, open) {
                (_, 0) => "F",
                (0, _) => "O",
                _ => "P",
            });
            total_prices.push(Some(total_price));
            order_dates.push(order_date);
            priorities.push(rng.pick(&PRIORITIES));
            order_clerks.push(format!("Clerk#{:09}", rng.int(1, clerks)));
            ship_priorities.push(0);
            let comment = match rng.int(0, 99) {
                0 => None,
                1 | 2 => Some(format!(
                    "{} special {} requests {}",
                    rng.words(1),
                    rng.words(2),
                    rng.words(2)
                )),
                _ => Some(rng.comment()),
            };
            order_comments.push(comment);
        }
        let orders = batch(vec![
            ("o_orderkey", false, int64(keys)),
            ("o_custkey", true, Arc::new(Int64Array::from(customers))),
            ("o_orderstatus", false, strings(statuses)),
            ("o_totalprice", false, decimals(total_prices)?),
            ("o_orderdate", false, dates(order_dates)),
            ("o_orderpriority", false, strings(priorities)),
            ("o_clerk", false, strings(order_clerks)),
            ("o_shippriority", false, int32(ship_priorities)),
            ("o_comment", true, nullable_strings(order_comments)),
        ])?;
        let lineitem = batch(vec![
            ("l_orderkey", false, int64(lines.orders)),
            ("l_partkey", false, int64(lines.parts)),
            ("l_suppkey", false, int64(lines.suppliers)),
            ("l_linenumber", false, int32(lines.numbers)),
            ("l_quantity", false, decimals(lines.quantities)?),
            ("l_extendedprice", false, decimals(lines.prices)?),
            ("l_discount", false, decimals(lines.discounts)?),
            ("l_tax", false, decimals(lines.taxes)?),
            ("l_returnflag", false, strings(lines.return_flags)),
            ("l_linestatus", false, strings(lines.line_statuses)),
            ("l_shipdate", false, dates(lines.ship_dates)),
            ("l_commitdate", false, dates(lines.commit_dates)),
            ("l_receiptdate", false, dates(lines.receipt_dates)),
            ("l_shipinstruct", false, strings(lines.instructions)),
            ("l_shipmode", false, strings(lines.ship_modes)),
            ("l_comment", true, nullable_strings(lines.comments)),
        ])?;
        Ok((orders, lineitem))
    }

    /// How the rows of a table are split into the partitions of a
    /// `MemTable` or into Parquet files.
    #[derive(Debug, Clone)]
    pub(crate) enum TableLayout {
        /// Every table is split into `partitions` partitions (or files) of
        /// about the same number of rows, in batches of `batch_size` rows.
        Even {
            partitions: usize,
            batch_size: usize,
        },
        /// The skewed layouts of the parity tests, see [`skewed_weights`]:
        /// partitions of very different sizes, some of them empty, in
        /// batches of irregular sizes (some of a single row).
        Skewed,
    }

    impl TableLayout {
        /// The relative sizes of the partitions of `table`.
        fn weights(&self, table: &str) -> Vec<usize> {
            match self {
                Self::Even { partitions, .. } => vec![1; (*partitions).max(1)],
                Self::Skewed => skewed_weights(table).to_vec(),
            }
        }

        /// The sizes of the batches of a partition, used in a cycle.
        fn batch_sizes(&self) -> Vec<usize> {
            match self {
                Self::Even { batch_size, .. } => vec![(*batch_size).max(1)],
                Self::Skewed => vec![5_000, 1, 2_048, 333, 8_192, 64],
            }
        }

        /// The rows of `batch` (a whole table) split into partitions of
        /// batches.
        pub(crate) fn partition(
            &self,
            table: &str,
            batch: &RecordBatch,
        ) -> Vec<Vec<RecordBatch>> {
            let weights = self.weights(table);
            let total = weights.iter().sum::<usize>().max(1);
            let rows = batch.num_rows();
            let batch_sizes = self.batch_sizes();
            let mut offset = 0;
            let mut cumulative = 0;
            weights
                .iter()
                .map(|weight| {
                    cumulative += weight;
                    let end = rows * cumulative / total;
                    let mut batches = vec![];
                    for size in batch_sizes.iter().cycle() {
                        if offset >= end {
                            break;
                        }
                        let len = (*size).min(end - offset);
                        batches.push(batch.slice(offset, len));
                        offset += len;
                    }
                    batches
                })
                .collect()
        }
    }

    /// The relative sizes of the skewed partitions (and Parquet files) of
    /// the tables: some are empty, and the number of partitions is below,
    /// equal to and above the 4 target partitions of the parity tests.
    fn skewed_weights(table: &str) -> &'static [usize] {
        match table {
            "nation" => &[4, 1],
            "supplier" => &[1, 0, 2],
            "part" => &[5, 3, 1, 1],
            "partsupp" => &[1, 1, 1, 7],
            "customer" => &[3, 1, 0],
            "orders" => &[4, 0, 4, 1],
            "lineitem" => &[8, 1, 0, 4, 2],
            _ => &[1],
        }
    }

    /// Register `tables` (name and rows) in `ctx` as `MemTable`s with the
    /// partitions of `layout`.
    pub(crate) fn register_memtables(
        ctx: &SessionContext,
        tables: &[(&'static str, RecordBatch)],
        layout: &TableLayout,
    ) -> Result<()> {
        for (name, batch) in tables {
            let partitions = layout.partition(name, batch);
            let table = MemTable::try_new(batch.schema(), partitions)?;
            ctx.register_table(*name, Arc::new(table))?;
        }
        Ok(())
    }

    /// A Parquet file of a table.
    #[derive(Debug)]
    pub(crate) struct ParquetFile {
        /// The table.
        pub(crate) table: &'static str,
        /// The name of the file.
        pub(crate) name: String,
        /// The content of the file.
        pub(crate) bytes: Vec<u8>,
    }

    /// Encode `tables` (name and rows) as Parquet files, one per partition
    /// of `layout` (an empty partition is a file without rows), with row
    /// groups of at most `row_group_rows` rows.
    pub(crate) fn encode_parquet(
        tables: &[(&'static str, RecordBatch)],
        layout: &TableLayout,
        row_group_rows: usize,
    ) -> Result<Vec<ParquetFile>> {
        let properties = WriterProperties::builder()
            .set_max_row_group_row_count(Some(row_group_rows))
            .build();
        let mut files = vec![];
        for (table, batch) in tables {
            for (i, batches) in layout.partition(table, batch).into_iter().enumerate() {
                let mut bytes = vec![];
                let mut writer = ArrowWriter::try_new(
                    &mut bytes,
                    batch.schema(),
                    Some(properties.clone()),
                )?;
                for batch in &batches {
                    writer.write(batch)?;
                }
                writer.close()?;
                files.push(ParquetFile {
                    table,
                    name: format!("part-{i}.parquet"),
                    bytes,
                });
            }
        }
        Ok(files)
    }

    /// Write `files` to `dir`, the files of every table in a directory named
    /// after the table.
    pub(crate) fn write_parquet(files: &[ParquetFile], dir: &Path) -> Result<()> {
        for file in files {
            let table_dir = dir.join(file.table);
            std::fs::create_dir_all(&table_dir)?;
            let mut out = File::create(table_dir.join(&file.name))?;
            std::io::Write::write_all(&mut out, &file.bytes)?;
        }
        Ok(())
    }

    /// Register the Parquet tables `tables` written to `dir` by
    /// [`write_parquet`] in `ctx`.
    pub(crate) async fn register_parquet(
        ctx: &SessionContext,
        dir: &Path,
        tables: &[&str],
    ) -> Result<()> {
        for table in tables {
            let path = dir.join(table);
            let path = path.to_str().ok_or_else(|| {
                DataFusionError::Internal(format!("not a UTF-8 path: {}", path.display()))
            })?;
            ctx.register_parquet(*table, path, ParquetReadOptions::default())
                .await?;
        }
        Ok(())
    }

