    /// A deterministic pseudo-random number generator (SplitMix64), so that
    /// the generated data never changes.
    pub(crate) struct Rng(u64);

    impl Rng {
        pub(crate) fn new(seed: u64) -> Self {
            Self(seed)
        }

        pub(crate) fn next_u64(&mut self) -> u64 {
            self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
            let mut z = self.0;
            z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
            z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
            z ^ (z >> 31)
        }

        /// A value in `low..=high`.
        pub(crate) fn int(&mut self, low: i64, high: i64) -> i64 {
            let span = (high - low) as u64 + 1;
            low + (self.next_u64() % span) as i64
        }

        /// `true` with a probability of `per_mille / 1000`.
        pub(crate) fn chance(&mut self, per_mille: u64) -> bool {
            self.next_u64() % 1000 < per_mille
        }

        /// A random element of `items`.
        pub(crate) fn pick<'a>(&mut self, items: &[&'a str]) -> &'a str {
            items[self.int(0, items.len() as i64 - 1) as usize]
        }

        /// `count` random words, separated by spaces.
        fn words(&mut self, count: i64) -> String {
            let mut text = String::new();
            for i in 0..count {
                if i > 0 {
                    text.push(' ');
                }
                text.push_str(self.pick(&WORD_LIST));
            }
            text
        }

        /// A comment of 3 to 10 words.
        fn comment(&mut self) -> String {
            let count = self.int(3, 10);
            self.words(count)
        }

        /// A random string of 10 to 40 characters.
        fn address(&mut self) -> String {
            let len = self.int(10, 40);
            (0..len)
                .map(|_| {
                    ADDRESS_CHARS[self.int(0, ADDRESS_CHARS.len() as i64 - 1) as usize]
                        as char
                })
                .collect()
        }

        /// A phone number of a customer or supplier of nation `nation`.
        fn phone(&mut self, nation: i64) -> String {
            format!(
                "{}-{}-{}-{}",
                nation + 10,
                self.int(100, 999),
                self.int(100, 999),
                self.int(1000, 9999)
            )
        }
    }

    /// The number of rows of the tables of a scale factor.
    #[derive(Debug, Clone, Copy)]
    pub(crate) struct Cardinalities {
        pub(crate) suppliers: i64,
        pub(crate) parts: i64,
        pub(crate) customers: i64,
        pub(crate) orders: i64,
    }

    impl Cardinalities {
        /// The cardinalities of TPC-H with scale factor `scale` (with at
        /// least 10 suppliers): 10,000 suppliers, 200,000 parts, 150,000
        /// customers and 1,500,000 orders (about 6,000,000 lineitems) per
        /// unit of scale.
        pub(crate) fn new(scale: f64) -> Self {
            let suppliers = ((10_000.0 * scale).round() as i64).max(10);
            Self {
                suppliers,
                parts: 20 * suppliers,
                customers: 15 * suppliers,
                orders: 150 * suppliers,
            }
        }
    }

    /// The retail price of a part, in cents.
    fn retail_price(partkey: i64) -> i64 {
        90_000 + (partkey / 10) % 20_001 + 100 * (partkey % 1_000)
    }

    /// The 4 distinct suppliers of a part (TPC-H's `PART_SUPP_BRIDGE`).
    fn part_suppliers(partkey: i64, suppliers: i64) -> [i64; 4] {
        let mut keys = [0; 4];
        for i in 0..4 {
            let step = suppliers / 4 + (partkey - 1) / suppliers;
            let mut key = (partkey + i as i64 * step) % suppliers + 1;
            while keys[..i].contains(&key) {
                key = key % suppliers + 1;
            }
            keys[i] = key;
        }
        keys
    }

    /// A batch of `columns` (name, nullable, values).
    fn batch(columns: Vec<(&str, bool, ArrayRef)>) -> Result<RecordBatch> {
        let fields = columns
            .iter()
            .map(|(name, nullable, array)| {
                Field::new(*name, array.data_type().clone(), *nullable)
            })
            .collect::<Vec<_>>();
        let arrays = columns.into_iter().map(|(_, _, array)| array).collect();
        Ok(RecordBatch::try_new(Arc::new(Schema::new(fields)), arrays)?)
    }

    fn int64(values: Vec<i64>) -> ArrayRef {
        Arc::new(Int64Array::from(values))
    }

    fn int32(values: Vec<i32>) -> ArrayRef {
        Arc::new(Int32Array::from(values))
    }

    fn dates(values: Vec<i32>) -> ArrayRef {
        Arc::new(Date32Array::from(values))
    }

    /// A column of strings, as `Utf8View` like the strings of DataFusion's
    /// SQL tables and Parquet scans.
    fn strings<S: AsRef<str>>(values: Vec<S>) -> ArrayRef {
        Arc::new(StringViewArray::from_iter_values(values))
    }

    fn nullable_strings(values: Vec<Option<String>>) -> ArrayRef {
        Arc::new(StringViewArray::from(values))
    }

    /// A `DECIMAL(15, 2)` column of `cents`.
    fn decimals(cents: Vec<Option<i64>>) -> Result<ArrayRef> {
        let array = cents
            .into_iter()
            .map(|value| value.map(i128::from))
            .collect::<Decimal128Array>()
            .with_precision_and_scale(15, 2)?;
        Ok(Arc::new(array))
    }

    /// The tables of a TPC-H database, each as a single batch.
    #[derive(Debug)]
    pub(crate) struct TpchData {
        pub(crate) cardinalities: Cardinalities,
        tables: Vec<(&'static str, RecordBatch)>,
    }

    impl TpchData {
        /// Generate the tables of scale factor `scale`.
        pub(crate) fn generate(scale: f64) -> Result<Self> {
            let cardinalities = Cardinalities::new(scale);
            let (orders, lineitem) = orders_and_lineitems(cardinalities)?;
            let tables = vec![
                ("region", region()?),
                ("nation", nation()?),
                ("supplier", supplier(cardinalities)?),
                ("part", part(cardinalities)?),
                ("partsupp", partsupp(cardinalities)?),
                ("customer", customer(cardinalities)?),
                ("orders", orders),
                ("lineitem", lineitem),
            ];
            Ok(Self {
                cardinalities,
                tables,
            })
        }

        /// The tables, with their names, in the order of [`TABLES`].
        pub(crate) fn tables(&self) -> &[(&'static str, RecordBatch)] {
            &self.tables
        }

        /// The table `name`.
        pub(crate) fn table(&self, name: &str) -> &RecordBatch {
            self.tables
                .iter()
                .find(|(table, _)| *table == name)
                .map(|(_, batch)| batch)
                .unwrap_or_else(|| panic!("no TPC-H table {name}"))
        }
    }

